"""HTML exporter — produces a self-contained HTML document with bionic styling baked in."""
from __future__ import annotations

from ..models import BionicSettings, DocumentModel
from ..transformer import transform_text_html


def export(doc: DocumentModel, settings: BionicSettings, title: str | None = None) -> tuple[bytes, str, str]:
    body_parts: list[str] = []
    open_list: str | None = None  # "ul" or "ol" or None
    for block in doc.blocks:
        if block.type == "list_item":
            tag = "ol" if block.ordered else "ul"
            if open_list != tag:
                if open_list:
                    body_parts.append(f"</{open_list}>")
                body_parts.append(f"<{tag}>")
                open_list = tag
        else:
            if open_list:
                body_parts.append(f"</{open_list}>")
                open_list = None

        rendered = transform_text_html(block.text or "", settings)
        if block.type == "heading":
            level = max(1, min(block.level or 2, 6))
            body_parts.append(f"<h{level}>{rendered}</h{level}>")
        elif block.type == "paragraph":
            body_parts.append(f"<p>{rendered}</p>")
        elif block.type == "list_item":
            body_parts.append(f"<li>{rendered}</li>")
        elif block.type == "blockquote":
            body_parts.append(f"<blockquote>{rendered}</blockquote>")
        elif block.type == "code":
            body_parts.append(f"<pre><code>{rendered}</code></pre>")
        elif block.type == "table_row":
            body_parts.append(f"<p class=\"row\">{rendered}</p>")
        elif block.type == "spacer":
            body_parts.append("<div class=\"spacer\"></div>")
    if open_list:
        body_parts.append(f"</{open_list}>")

    safe_title = (title or doc.filename or "Document").strip()
    html = _TEMPLATE.format(title=_escape(safe_title), body="\n".join(body_parts))
    return html.encode("utf-8"), "text/html", _safe_filename(doc.filename, ".html")


def _escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _safe_filename(name: str, new_ext: str) -> str:
    from pathlib import Path

    stem = Path(name).stem or "document"
    return f"{stem}.bionic{new_ext}"


